const {chromium}=require('playwright');import {serve} from './serve.mjs';
const srv=await serve();const base=`http://127.0.0.1:${srv.address().port}/`;
const b=await chromium.launch({args:['--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist']});
const ctx=await b.newContext({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
const pg=await ctx.newPage();pg.on('console',m=>console.log('C',m.type(),m.text().slice(0,300)));pg.on('pageerror',e=>console.log('PAGEERR',e.message));
await pg.route(/fonts\.(googleapis|gstatic)\.com|telegram\.org|mc\.yandex/,r=>r.fulfill({status:200,body:''}));
await pg.addInitScript(()=>{localStorage.setItem('garage-state',JSON.stringify({onboarded:true}));});
await pg.goto(base);await pg.waitForFunction(()=>window.__garageReady,null,{timeout:120000});
await pg.waitForTimeout(2000);
